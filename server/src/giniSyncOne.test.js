function headerValue(headers, name) {
  if (!headers) return "";
  const found = Object.keys(headers).find((key) => key.toLowerCase() === name.toLowerCase());
  return found ? String(headers[found]) : "";
}

function mockResponse(status, body, contentType = "application/json", extraHeaders = {}) {
  const text = typeof body === "string" ? body : JSON.stringify(body);
  const headers = {
    "content-type": contentType,
    ...Object.fromEntries(Object.entries(extraHeaders).map(([key, value]) => [String(key).toLowerCase(), value])),
  };
  return {
    status,
    headers: { get: (name) => headers[String(name).toLowerCase()] ?? null },
    async text() {
      return text;
    },
  };
}

function installFetch() {
  calls = [];
  setGiniFetch(async (url, options = {}) => {
    const method = String(options.method || "GET").toUpperCase();
    const target = String(url);
    calls.push({ method, url: target, options });
    if (method !== "GET" && method !== "POST") throw new Error(`unexpected ${method}`);
    if (method === "POST" && !allowPost) throw new Error(`GINI write attempted: ${method} ${target}`);
    if (target.endsWith(GINI_PING_PATH)) return mockResponse(200, { data: { ok: true } });
    if (target.split("?")[0].endsWith(GINI_CATEGORIES_PATH)) return mockResponse(200, LIVE_TREE);
    if (method === "POST" && target.split("?")[0].endsWith(GINI_PRODUCTS_PATH)) {
      if (loseCreateResponse) {
        if (recoverSkuAfterLostCreate) existingSku = recoverSkuAfterLostCreate;
        throw new Error("connection lost before a GINI response");
      }
      const signature = headerValue(options.headers, "x-signature");
      if (postMode === "edge") {
        const html = `<HTML><HEAD><TITLE>ERROR: The request could not be satisfied</TITLE></HEAD><BODY><H1>403 ERROR</H1><H2>The request could not be satisfied.</H2>Request blocked. ${SECRET} ${CLIENT_ID} ${signature} cookie=session-token ${"Z".repeat(4000)} Generated by cloudfront (CloudFront)</BODY></HTML>`;
        return mockResponse(403, html, "text/html", { "x-request-id": "edge-req-1" });
      }
      if (postMode === "json-error") {
        return mockResponse(
          403,
          {
            error: "Client account is inactive",
            message: "should not win",
            detail: `${SECRET} ${CLIENT_ID} ${signature} ${"Q".repeat(2000)}`,
          },
          "application/json",
          { "x-request-id": "api-error-1" }
        );
      }
      if (postMode === "json-message") {
        return mockResponse(
          403,
          {
            message: "The name field is required.",
            detail: `${SECRET} ${signature} ${"Q".repeat(2000)}`,
          },
          "application/json",
          { "x-request-id": "api-message-1" }
        );
      }
      if (postMode === "other") {
        return mockResponse(422, {
          message: "The quantity field is invalid.",
          detail: `${SECRET} ${signature} ${"Q".repeat(2000)}`,
        });
      }
      return mockResponse(201, { data: { id: createdId, sku: "LP-ID141232" } });
    }
    if (method === "GET" && target.includes("/products/")) {
      if (existingSku) {
        return mockResponse(200, { data: { id: 77, sku: existingSku, name: "Already there" } });
      }
      return mockResponse(404, { message: "Product not found." });
    }
    if (method === "GET" && target.includes("/products?")) {
      return mockResponse(200, { data: [], meta: { last_page: 1, total: 0 } });
    }
    throw new Error(`unexpected ${target}`);
  });
}

function installMedia() {
  mediaCalls = [];
  setGiniMediaFetch(async (url) => {
    mediaCalls.push(String(url));
    if (invalidImage) {
      return {
        status: 200,
        headers: { get: () => "text/html" },
        async arrayBuffer() {
          return Buffer.from("<html>not an image</html>");
        },
      };
    }
    return {
      status: 200,
      headers: {
        get(name) {
          return String(name).toLowerCase() === "content-type" ? "image/png" : null;
        },
      },
      async arrayBuffer() {
        return PNG;
      },
    };
  });
}

async function call(method, urlPath, { body, auth = true } = {}) {
  const { port } = server.address();
  const response = await fetch(`http://127.0.0.1:${port}${urlPath}`, {
    method,
    headers: {
      ...(auth ? { Authorization: `Bearer ${token}` } : {}),
      ...(body ? { "Content-Type": "application/json" } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const json = await response.json().catch(() => ({}));
  return { status: response.status, json, raw: JSON.stringify(json) };
}


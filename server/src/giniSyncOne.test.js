async function connectGini() {
  allowPost = false;
  installFetch();
  await call("PUT", "/api/admin/platforms/gini/connection", {
    body: { baseUrl: GINI_DEFAULT_BASE_URL, clientId: CLIENT_ID, clientSecret: SECRET },
  });
  const tested = await call("POST", "/api/admin/platforms/gini/connection/test", {
    body: { baseUrl: GINI_DEFAULT_BASE_URL, clientId: CLIENT_ID, clientSecret: SECRET },
  });
  assert.equal(tested.json.status, "connected");
  calls = [];
}

function formEntries(options) {
  const rows = [];
  for (const [key, value] of options.body.entries()) {
    if (typeof value === "string") rows.push([key, value]);
    else rows.push([key, { file: true, type: value.type, name: value.name, size: value.size }]);
  }
  return rows;
}

describe("GINI Sync 1 planning rules", () => {
  it("normalizes itemCode the way GINI stores a SKU and treats case as the same identity", () => {
    assert.equal(normalizeGiniItemCode("  LP-ID141232  "), "LP-ID141232");
    assert.equal(normalizeGiniItemCode("AB C"), "AB-C");
    assert.equal(giniSkuKey("AB C"), giniSkuKey("ab-c"));
    assert.notEqual(giniSkuKey("LP-ID141232"), giniSkuKey("LP-ID141231"));
  });

  it("keeps the existing 250 IQD rounding and a 0% commission price", () => {
    assert.equal(applyCommissionRate(6500, 0), 6500);
    assert.equal(applyCommissionRate(1000, 10), 1250);
    assert.equal(applyCommissionRate(1001, 0), 1250);
  });

  it("collapses one sellable variant and blocks complex variant structures", () => {
    const simple = assessSimpleProduct({
      itemCode: "LP-ID141232",
      sellingPrice: 6500,
      variants: simpleVariant(),
    });
    assert.equal(simple.giniMode, "SIMPLE_PRODUCT");
    assert.equal(simple.brownStoreVariantsCollapsed, 1);
    assert.deepEqual(simple.blockers, []);

    const many = assessSimpleProduct({
      itemCode: "LP-ID141232",
      sellingPrice: 6500,
      variants: [...simpleVariant(), ...simpleVariant()],
    });
    assert.equal(many.simple, false);
    assert.deepEqual(many.blockers, ["gini_variant_mapping_required"]);

    const sizes = assessSimpleProduct({
      itemCode: "LP-ID141232",
      sellingPrice: 6500,
      variants: [
        {
          color: { en: "white" },
          sizes: [
            { size: "small", stockQuantity: 1 },
            { size: "medium", stockQuantity: 1 },
          ],
        },
      ],
    });
    assert.deepEqual(sizes.blockers, ["gini_variant_mapping_required"]);

    const colors = assessSimpleProduct({
      itemCode: "LP-ID141232",
      sellingPrice: 6500,
      variants: [
        {
          color: { en: "white" },
          sizes: [{ size: "medium", stockQuantity: 1, color: { en: "black" } }],
        },
      ],
    });
    assert.deepEqual(colors.blockers, ["gini_variant_mapping_required"]);

    const sku = assessSimpleProduct({
      itemCode: "LP-ID141232",
      sellingPrice: 6500,
      variants: simpleVariant(5, { sku: "OTHER-SKU" }),
    });
    assert.deepEqual(sku.blockers, ["gini_variant_mapping_required"]);

    const price = assessSimpleProduct({
      itemCode: "LP-ID141232",
      sellingPrice: 6500,
      variants: simpleVariant(5, { price: 9000 }),
    });
    assert.deepEqual(price.blockers, ["gini_variant_mapping_required"]);
    assert.equal(decideSyncAction(["existing_gini_product"]).action, "UPDATE_AVAILABLE");
    assert.equal(decideSyncAction(["existing_gini_product", "missing_image"]).action, "BLOCKED");
  });

  it("rejects an invalid image and accepts a real PNG signature", () => {
    assert.equal(sniffImage(PNG, "image/png")?.mime, "image/png");
    assert.equal(sniffImage(Buffer.from("<html>"), "text/html"), null);
    assert.equal(sniffImage(Buffer.from("<html>"), "image/png"), null);
  });
});


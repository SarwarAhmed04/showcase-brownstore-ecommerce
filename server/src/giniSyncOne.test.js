  async function sendDiagnosed(itemCode, mode) {
    const product = await makeProduct({ itemCode, ibsherId: itemCode });
    await mapCollection();
    calls = [];
    const preview = await call("POST", "/api/admin/platforms/gini/sync-one/preview", {
      body: { productId: String(product._id) },
    });
    assert.equal(preview.status, 200);
    assert.equal(preview.json.action, "CREATE");
    assert.equal(calls.every((item) => item.method === "GET"), true);
    allowPost = true;
    postMode = mode;
    calls = [];
    const sent = await call("POST", "/api/admin/platforms/gini/sync-one/send", {
      body: { productId: String(product._id), confirm: true, previewToken: preview.json.previewToken },
    });
    const post = calls.find((item) => item.method === "POST");
    const postCount = calls.filter((item) => item.method === "POST").length;
    const signature = headerValue(post?.options.headers, "x-signature");
    calls = [];
    const retry = await call("POST", "/api/admin/platforms/gini/sync-one/send", {
      body: { productId: String(product._id), confirm: true, previewToken: preview.json.previewToken },
    });
    const audit = await GiniSyncOneAudit.findOne({ productId: String(product._id) }).lean();
    return { sent, postCount, signature, retry, audit, postsAfter: calls.filter((item) => item.method === "POST").length };
  }

  function assertNoSecrets(raw, signature) {
    assert.equal(raw.includes(SECRET), false);
    assert.equal(raw.includes(CLIENT_ID), false);
    assert.equal(raw.includes("clientSecret"), false);
    assert.equal(raw.includes("X-SIGNATURE"), false);
    assert.equal(signature.length > 8, true);
    assert.equal(raw.includes(signature), false);
    assert.equal(raw.includes("cookie=session-token"), false);
  }


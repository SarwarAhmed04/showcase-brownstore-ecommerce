const HOLD_KEYS = new Set(GINI_HISTORICAL_HOLD_SKUS.map((sku) => giniSkuKey(sku)));

export function isGiniHistoricalHoldSku(sku) {
  const key = giniSkuKey(sku);
  return Boolean(key) && HOLD_KEYS.has(key);
}
